#ifndef HYPE_DEVICES_TPM_SSDT_AML_H
#define HYPE_DEVICES_TPM_SSDT_AML_H

/*
 * #433: the AML body of a minimal SSDT declaring \_SB.TPM with _HID "MSFT0101" and a _CRS
 * covering the CRB window at 0xFED40000. This is the ACPI device node Linux's tpm_crb and
 * Windows' fTPM detection bind to -- the TPM2 table alone is not enough for either. Emitted as
 * a SEPARATE, per-VM SSDT (not folded into the shared static DSDT) so a VM with no TPM never
 * advertises one. Compiled from tpm_ssdt.asl by iasl; only the body follows the 36-byte SDT
 * header, which hype fills itself (same split as devices/dsdt_aml.h).
 *
 * Regenerate: iasl -tc tpm_ssdt.asl, then strip the first 36 bytes.
 */

#define HYPE_TPM_SSDT_AML_BODY_LEN 69u

static const unsigned char hype_tpm_ssdt_aml_body[HYPE_TPM_SSDT_AML_BODY_LEN] = {
    0x10, 0x44, 0x04, 0x5c, 0x5f, 0x53, 0x42, 0x5f, 0x5b, 0x82, 0x3b, 0x54,
    0x50, 0x4d, 0x5f, 0x08, 0x5f, 0x48, 0x49, 0x44, 0x0d, 0x4d, 0x53, 0x46,
    0x54, 0x30, 0x31, 0x30, 0x31, 0x00, 0x08, 0x5f, 0x55, 0x49, 0x44, 0x00,
    0x08, 0x5f, 0x43, 0x52, 0x53, 0x11, 0x11, 0x0a, 0x0e, 0x86, 0x09, 0x00,
    0x01, 0x00, 0x00, 0xd4, 0xfe, 0x00, 0x10, 0x00, 0x00, 0x79, 0x00, 0x14,
    0x09, 0x5f, 0x53, 0x54, 0x41, 0x00, 0xa4, 0x0a, 0x0f,
};

#endif /* HYPE_DEVICES_TPM_SSDT_AML_H */
